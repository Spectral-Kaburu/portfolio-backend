//! Shared types for M2: digest, evidence map, draft, and AI config.
//!
//! RUST NOTE: These types are shared across multiple modules and must be
//! serializable to JSON for the draft output format.

use anyhow::Context;
use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};

/// AI client configuration from config.toml.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[allow(dead_code)]
pub struct AiConfig {
    pub base_url: String,
    pub api_key_env: String,
    pub model: String,
    pub requests_per_minute: u32,
    pub max_retries: u32,
    pub connect_timeout_secs: u64,
    pub read_timeout_secs: u64,
    pub temperature: f64,
    pub max_tokens: u32,
    pub digest_max_bytes: usize,
}

impl Default for AiConfig {
    fn default() -> Self {
        Self {
            base_url: "https://integrate.api.nvidia.com/v1".to_string(),
            api_key_env: "NVIDIA_API_KEY".to_string(),
            model: String::new(),
            requests_per_minute: 20,
            max_retries: 4,
            connect_timeout_secs: 10,
            read_timeout_secs: 120,
            temperature: 0.2,
            max_tokens: 1500,
            digest_max_bytes: 6000,
        }
    }
}

impl AiConfig {
    /// Returns the API key from the environment variable.
    /// Does NOT log or print the key value.
    pub fn api_key(&self) -> anyhow::Result<String> {
        std::env::var(&self.api_key_env)
            .with_context(|| format!("Please set the {} environment variable", self.api_key_env))
    }
}

/// Status based on last commit date.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
#[allow(dead_code)]
pub enum ProjectStatus {
    Active,
    Dormant,
}

/// Language for digest (renormalized to 100%).
#[derive(Debug, Clone, Serialize, Deserialize)]
#[allow(dead_code)]
pub struct DigestLanguage {
    pub name: String,
    pub share: f64, // Renormalized to 100%
}

/// Evidence reference in the draft.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[allow(dead_code)]
pub struct EvidenceRef {
    pub id: String,    // E1, E2, etc.
    pub r#ref: String, // commit:hash, readme, manifest:kind, stats
}

/// A claim with evidence references.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[allow(dead_code)]
pub struct Claim {
    pub text: String,
    pub evidence: Vec<String>, // Evidence ids E1, E2, etc.
}

/// Project overview generated by AI.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[allow(dead_code)]
pub struct ProjectOverview {
    pub repo_id: String,
    pub name: String,
    pub status: ProjectStatus,
    pub overview: String,
    pub claims: Vec<Claim>,
    pub related: Vec<String>,
    pub claims_dropped: u32,
    pub failure: Option<String>,
}

/// Recent activity summary generated by AI.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[allow(dead_code)]
pub struct RecentActivity {
    pub summary: String,
    pub claims: Vec<RecentActivityClaim>,
    pub failure: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[allow(dead_code)]
pub struct RecentActivityClaim {
    pub text: String,
    pub projects: Vec<String>,
}

/// The complete draft output.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[allow(dead_code)]
pub struct Draft {
    pub schema_version: u32,
    pub enriched_at: DateTime<Utc>,
    pub model: String,
    pub prompt_version: String,
    pub projects: Vec<ProjectOverview>,
    pub recent_activity: RecentActivity,
}

impl Default for Draft {
    fn default() -> Self {
        Self {
            schema_version: 1,
            enriched_at: Utc::now(),
            model: String::new(),
            prompt_version: String::new(),
            projects: Vec::new(),
            recent_activity: RecentActivity {
                summary: String::new(),
                claims: Vec::new(),
                failure: None,
            },
        }
    }
}

